#下面是这九种命令的描述：
#列表 = []
#指针 = ""
#<a：将列表指针向左移动a位。
#>a：将列表指针向右移动a位。
#+a：将当前列表指针所指单元的值增加a。
#-a：将当前列表指针所指单元的值减少a。
#.：输出当前列表位的值作为UTF-8字符。
#,：从输入读取一个UTF-8字符并存储到当前列表位。
#[：如果当前单元值为零，跳转到匹配的]之后的下一条指令。
#]：如果当前单元值非零，跳转回匹配的[之后的下一条指令。
#|name=k:定义新命令。name是utf-8字符，k是由以上命令组合而成的命令。
#|name:调用已定义的命令name。


列表 = {}
指针 = 0
自定义命令 = {}

def 符语(命令序列):
    global 列表, 指针, 自定义命令
    
    i = 0
    while i < len(命令序列):
        命令 = 命令序列[i]
        
        if 命令.startswith('<'):
            # 向左移动指针
            移动量 = int(命令[1:])
            指针 = max(0, 指针 - 移动量)
        
        elif 命令.startswith('>'):
            # 向右移动指针
            移动量 = int(命令[1:])
            指针 += 移动量
            # 确保指针位置有值
            if 指针 not in 列表:
                列表[指针] = 0
        
        elif 命令.startswith('+'):
            # 增加当前值
            增加值 = int(命令[1:])
            if 指针 not in 列表:
                列表[指针] = 0
            列表[指针] += 增加值
        
        elif 命令.startswith('-'):
            # 减少当前值
            减少值 = int(命令[1:])
            if 指针 not in 列表:
                列表[指针] = 0
            列表[指针] -= 减少值
        
        elif 命令 == '.':
            # 输出当前值作为字符
            if 指针 in 列表:
                print(chr(列表[指针]), end='')
        
        elif 命令 == ',':
            # 读取输入
            输入字符 = input("~")[0]  # 只取第一个字符
            列表[指针] = ord(输入字符)
        
        elif 命令 == '[':
            # 循环开始 - 如果当前值为0，跳到匹配的]之后
            if 指针 not in 列表 or 列表[指针] == 0:
                深度 = 1
                j = i + 1
                while j < len(命令序列) and 深度 > 0:
                    if 命令序列[j] == '[':
                        深度 += 1
                    elif 命令序列[j] == ']':
                        深度 -= 1
                    j += 1
                i = j - 1  # 跳到]之后
            else:
                i += 1  # 继续执行循环体内的命令
        
        elif 命令 == ']':
            # 循环结束 - 如果当前值非0，跳回匹配的[之后
            if 指针 in 列表 and 列表[指针] != 0:
                深度 = 1
                j = i - 1
                while j >= 0 and 深度 > 0:
                    if 命令序列[j] == ']':
                        深度 += 1
                    elif 命令序列[j] == '[':
                        深度 -= 1
                    j -= 1
                i = j + 1  # 跳回[之后
            else:
                i += 1  # 退出循环
        
        elif 命令.startswith('|') and '=' in 命令:
            # 定义新命令: |name=k
            部分 = 命令[1:].split('=', 1)
            name = 部分[0]
            k = 部分[1]
            自定义命令[name] = 解析命令序列(k)  # 使用解析命令序列函数来解析命令序列
        
        elif 命令.startswith('|'):
            # 调用已定义命令: |name
            name = 命令[1:]
            if name in 自定义命令:
                # 递归执行自定义命令
                符语(自定义命令[name])
            else:
                print(f"Error: Undefined command '{name}'")
        
        else:
            i += 1
            continue
        
        i += 1

def 解析命令序列(命令字符串):
    """将命令字符串解析为命令列表"""
    命令列表 = []
    i = 0
    
    while i < len(命令字符串):
        char = 命令字符串[i]
        
        if char in ['<', '>', '+', '-']:
            # 处理带数字的命令
            j = i + 1
            while j < len(命令字符串) and 命令字符串[j].isdigit():
                j += 1
            命令列表.append(命令字符串[i:j])
            i = j
        
        elif char in ['.', ',', '[', ']']:
            # 处理单字符命令
            命令列表.append(char)
            i += 1
        
        elif char == '|':
            # 处理自定义命令
            j = i + 1
            # 找到命令的结束（空格或字符串结束）
            while j < len(命令字符串) and 命令字符串[j] not in [';']:
                j += 1
            命令列表.append(命令字符串[i:j])
            i = j
        
        else:
            # 跳过空格和其他字符
            i += 1
    
    return 命令列表

